function generateStatementPDF(tenant,year=new Date().getFullYear()){
  nestiqShowNotif('Generating PDF...','warning');
  try{
    const { jsPDF }=window.jspdf;
    const doc=new jsPDF({unit:'mm',format:'a4',orientation:'portrait'});
    const prop=propertyForTenant(tenant);
    let y=pdfGenerator.addHeader(doc,`PAYMENT STATEMENT ${year}`);
    const all=(tenant.payments||[]).filter(p=>String(p.date||'').startsWith(String(year))).sort((a,b)=>String(b.date).localeCompare(String(a.date)));
    const total=all.reduce((s,p)=>s+Number(p.amount||0),0);
    const onTime=all.filter(p=>new Date(p.date).getDate()<=Number(tenant.monthlyDueDate||1)).length;
    const late=Math.max(all.length-onTime,0);
    const w=doc.internal.pageSize.getWidth()-(pdfGenerator.marginX*2);
    doc.setDrawColor(225,225,225); doc.roundedRect(pdfGenerator.marginX,y,w,24,2,2,'S');
    doc.setFontSize(10); doc.setTextColor(...pdfGenerator.colors.dark);
    doc.text(`Tenant: ${tenant.name}`,pdfGenerator.marginX+4,y+7);
    doc.text(`Unit: ${tenant.unit}`,pdfGenerator.marginX+4,y+13);
    doc.text(`Period: 1 January ${year} to 31 December ${year}`,pdfGenerator.marginX+4,y+19);
    doc.text(`Property: ${tenant.property}`,pdfGenerator.marginX+w/2,y+7);
    doc.text(`Address: ${prop.addr||'—'}`,pdfGenerator.marginX+w/2,y+13);
    y+=30;
    const statW=(w-6)/4;
    const stats=[['Total Paid',`R${total.toLocaleString('en-ZA')}`],['Payments Made',String(all.length)],['On Time',String(onTime)],['Late',String(late)]];
    stats.forEach((s,i)=>{
      const x=pdfGenerator.marginX+(i*(statW+2));
      doc.setFillColor(248,248,248); doc.roundedRect(x,y,statW,14,1.5,1.5,'F');
      doc.setFontSize(8); doc.setTextColor(...pdfGenerator.colors.gray); doc.text(s[0],x+2,y+5);
      doc.setFontSize(10); doc.setTextColor(...pdfGenerator.colors.dark); doc.text(s[1],x+2,y+11);
    });
    y+=19;
    if(!all.length){
      doc.setTextColor(...pdfGenerator.colors.gray);
      doc.text(`No payments recorded for ${year}`,pdfGenerator.marginX,y);
      y+=8;
    }else{
      const rows=all.map(p=>[
        p.month||new Date(p.date).toLocaleDateString('en-ZA',{month:'short'}),
        isoToPretty(p.date),
        `R${Number(p.amount||0).toLocaleString('en-ZA')}`,
        p.method||'EFT',
        p.receiptNo||'—',
        String(p.status||'paid').toUpperCase()
      ]);
      y=pdfGenerator.addTable(doc,y,['Month','Date','Amount','Method','Receipt No','Status'],rows,{colRatios:[1.1,1.2,1.1,1.1,1.6,0.9],repeatTitle:`PAYMENT STATEMENT ${year}`});
      doc.setFont('helvetica','bold'); doc.setTextColor(...pdfGenerator.colors.dark); doc.text(`Total: R${total.toLocaleString('en-ZA')}`,pdfGenerator.marginX,y); y+=8;
    }
    const expected=Number(tenant.rent||0)*12;
    const outstanding=Math.max(0,expected-total);
    if(outstanding>0){
      doc.setFillColor(255,240,240); doc.roundedRect(pdfGenerator.marginX,y,w,10,1.5,1.5,'F');
      doc.setTextColor(...pdfGenerator.colors.overdue); doc.setFont('helvetica','bold');
      doc.text(`Outstanding Balance: R${outstanding.toLocaleString('en-ZA')}`,pdfGenerator.marginX+3,y+6.5);
      y+=14;
    }
    doc.setFont('helvetica','normal'); doc.setTextColor(...pdfGenerator.colors.gray); doc.setFontSize(9);
    doc.text(`This statement was generated on ${new Date().toLocaleDateString('en-ZA')}.`,pdfGenerator.marginX,270);
    doc.text(`For queries or disputes please contact ${landlordSettings.email||'—'}`,pdfGenerator.marginX,275);
    finalizePdf(doc,`statement-${tenant.name.replace(/\s+/g,'-')}-${year}.pdf`);
  }catch(_err){
    nestiqShowNotif('PDF generation failed','error');
  }
}

