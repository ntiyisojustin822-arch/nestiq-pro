const pdfGenerator={
  colors:{
    gold:[201,168,76],
    dark:[14,17,23],
    gray:[120,120,120],
    light:[246,246,246],
    white:[255,255,255],
    paid:[90,122,96],
    overdue:[196,106,58]
  },
  marginX:14,
  addHeader(doc,title){
    const w=doc.internal.pageSize.getWidth();
    doc.setFont('helvetica','bold');
    doc.setFontSize(22);
    doc.setTextColor(...this.colors.gold);
    doc.text('NestIQ Pro', this.marginX, 16);
    doc.setFont('helvetica','normal');
    doc.setFontSize(14);
    doc.setTextColor(...this.colors.dark);
    doc.text(title, this.marginX, 24);
    doc.setDrawColor(...this.colors.gold);
    doc.setLineWidth(0.8);
    doc.line(this.marginX, 28, w-this.marginX, 28);
    doc.setFontSize(9);
    doc.setTextColor(...this.colors.gray);
    doc.text(`Generated: ${new Date().toLocaleDateString('en-ZA')}`, w-this.marginX, 10, {align:'right'});
    return 34;
  },
  addFooter(doc,pageNum,totalPages){
    const w=doc.internal.pageSize.getWidth();
    const h=doc.internal.pageSize.getHeight();
    doc.setDrawColor(210,210,210);
    doc.setLineWidth(0.3);
    doc.line(this.marginX, h-14, w-this.marginX, h-14);
    doc.setFont('helvetica','normal');
    doc.setFontSize(8);
    doc.setTextColor(...this.colors.gray);
    doc.text('Generated by NestIQ Pro', this.marginX, h-9);
    doc.text(`Page ${pageNum} of ${totalPages}`, w-this.marginX, h-9, {align:'right'});
    doc.text('Confidential - For recipient only', w/2, h-9, {align:'center'});
  },
  addSectionTitle(doc,y,title){
    const w=doc.internal.pageSize.getWidth()-(this.marginX*2);
    doc.setFillColor(...this.colors.light);
    doc.roundedRect(this.marginX, y, w, 9, 1.5, 1.5, 'F');
    doc.setFillColor(...this.colors.gold);
    doc.rect(this.marginX, y, 3, 9, 'F');
    doc.setFont('helvetica','bold');
    doc.setFontSize(11);
    doc.setTextColor(...this.colors.dark);
    doc.text(title, this.marginX+6, y+6);
    return y+13;
  },
  addTable(doc,y,headers,rows,options={}){
    const w=doc.internal.pageSize.getWidth()-(this.marginX*2);
    const colRatios=options.colRatios||headers.map(()=>1);
    const totalRatio=colRatios.reduce((s,v)=>s+v,0);
    const colWidths=colRatios.map(r=>w*(r/totalRatio));
    const rowH=7;
    const drawHeader=()=>{
      doc.setFillColor(...this.colors.dark);
      doc.setTextColor(...this.colors.white);
      doc.setFont('helvetica','bold');
      let x=this.marginX;
      headers.forEach((h,i)=>{
        doc.rect(x,y,colWidths[i],rowH,'F');
        doc.text(String(h),x+1.5,y+4.8);
        x+=colWidths[i];
      });
      y+=rowH;
    };
    const pageH=doc.internal.pageSize.getHeight();
    drawHeader();
    doc.setFont('helvetica','normal');
    rows.forEach((r,idx)=>{
      if(y>pageH-24){
        doc.addPage();
        y=this.addHeader(doc, options.repeatTitle||'');
        drawHeader();
      }
      const fill=idx%2===0?[255,255,255]:[248,248,248];
      doc.setFillColor(...fill);
      doc.setTextColor(...this.colors.dark);
      let x=this.marginX;
      r.forEach((c,i)=>{
        doc.rect(x,y,colWidths[i],rowH,'F');
        doc.text(String(c??''),x+1.5,y+4.8);
        x+=colWidths[i];
      });
      y+=rowH;
    });
    doc.setDrawColor(...this.colors.gold);
    doc.setLineWidth(0.4);
    doc.rect(this.marginX,y-(rows.length*rowH)-rowH,w,(rows.length*rowH)+rowH,'S');
    return y+6;
  },
  addStamp(doc,text,colorHex,x,y){
    const rgb=colorHex.replace('#','').match(/.{1,2}/g).map(v=>parseInt(v,16));
    doc.setTextColor(rgb[0],rgb[1],rgb[2]);
    doc.setFont('helvetica','bold');
    doc.setFontSize(54);
    doc.text(text,x,y,{angle:28,align:'center'});
    doc.setTextColor(...this.colors.dark);
  }
};

function finalizePdf(doc, filename, opts){
  opts=opts&&typeof opts==='object'?opts:{};
  try{
    const pages=doc.getNumberOfPages();
    for(let i=1;i<=pages;i++){
      doc.setPage(i);
      pdfGenerator.addFooter(doc,i,pages);
    }
    if(opts.returnDataUrl) return doc.output('datauristring');
    if(opts.preview!==false) doc.output('dataurlnewwindow');
    if(!opts.previewOnly) doc.save(filename);
    if(!opts.silent) nestiqShowNotif(opts.previewOnly?'PDF opened':'PDF ready','success');
  }catch(_err){
    if(!opts.silent) nestiqShowNotif('PDF generation failed','error');
  }
  return null;
}

